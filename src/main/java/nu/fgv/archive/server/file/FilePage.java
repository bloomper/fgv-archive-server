package nu.fgv.archive.server.file;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;
import lombok.Getter;
import lombok.Setter;

/**
 * The text of one page of a file, under a full-text index, so that search hits show their page. Files without pages,
 * e.g. DOCX, have their whole text as page 0.
 *
 * @author Anders Jacobsson
 * @since 1.0
 */
@Entity
@Table(name = "file_page")
@Getter
@Setter
public class FilePage {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "file_id", nullable = false)
    private ArchiveFile file;

    @Column(name = "page", nullable = false)
    private int page;

    @Column(name = "text", nullable = false)
    private String text;
}
